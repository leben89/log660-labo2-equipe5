CREATE TABLE DW_DIM_CLIENT (
    CLIENT_KEY              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLIENT_ID_SOURCE        NUMBER       NOT NULL,
    NOM_COMPLET             VARCHAR2(160) NOT NULL,
    AGE_ANNEES              NUMBER(3),
    AGE_MIN_GROUPE          NUMBER(3),
    GROUPE_AGE              VARCHAR2(20) NOT NULL,
    DATE_PREMIERE_LOCATION  DATE,
    CODE_POSTAL             VARCHAR2(20) NOT NULL,
    VILLE                   VARCHAR2(100) NOT NULL,
    PROVINCE                VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_DW_DIM_CLIENT PRIMARY KEY (CLIENT_KEY),
    CONSTRAINT UQ_DW_CLIENT_SOURCE UNIQUE (CLIENT_ID_SOURCE),
    CONSTRAINT CK_DW_CLIENT_AGE CHECK (AGE_ANNEES IS NULL OR AGE_ANNEES >= 0)
);

CREATE TABLE DW_DIM_TEMPS (
    TEMPS_KEY            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DATE_COMPLETE        DATE         NOT NULL,
    HEURE                NUMBER(2)    NOT NULL,
    JOUR_SEMAINE         VARCHAR2(12) NOT NULL,
    NUM_JOUR_SEMAINE     NUMBER(1)    NOT NULL,
    MOIS_ANNEE           VARCHAR2(12) NOT NULL,
    NUM_MOIS             NUMBER(2)    NOT NULL,
    ANNEE                NUMBER(4)    NOT NULL,
    CONSTRAINT PK_DW_DIM_TEMPS PRIMARY KEY (TEMPS_KEY),
    CONSTRAINT UQ_DW_TEMPS UNIQUE (DATE_COMPLETE, HEURE),
    CONSTRAINT CK_DW_TEMPS_HEURE CHECK (HEURE BETWEEN 0 AND 23),
    CONSTRAINT CK_DW_TEMPS_JOUR CHECK (NUM_JOUR_SEMAINE BETWEEN 1 AND 7),
    CONSTRAINT CK_DW_TEMPS_MOIS CHECK (NUM_MOIS BETWEEN 1 AND 12)
);

CREATE TABLE DW_DIM_FILM (
    FILM_KEY              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    FILM_ID_SOURCE        NUMBER        NOT NULL,
    TITRE_COMPLET         VARCHAR2(300) NOT NULL,
    ANNEE_SORTIE          NUMBER(4)     NOT NULL,
    ORIGINE               VARCHAR2(5)   NOT NULL,
    GENRE_ACTION          NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_ADVENTURE       NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_ANIMATION       NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_BIOGRAPHY       NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_COMEDY          NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_CRIME           NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_DOCUMENTARY     NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_DRAMA           NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_FAMILY          NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_FANTASY         NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_FILM_NOIR       NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_HISTORY         NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_HORROR          NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_MUSIC           NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_MUSICAL         NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_MYSTERY         NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_ROMANCE         NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_SCI_FI          NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_SPORT           NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_THRILLER        NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_WAR             NUMBER(1) DEFAULT 0 NOT NULL,
    GENRE_WESTERN         NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DW_DIM_FILM PRIMARY KEY (FILM_KEY),
    CONSTRAINT UQ_DW_FILM_SOURCE UNIQUE (FILM_ID_SOURCE),
    CONSTRAINT CK_DW_FILM_ORIGINE CHECK (ORIGINE IN ('USA', 'AUTRE')),
    CONSTRAINT CK_DW_FILM_GENRES CHECK (
        GENRE_ACTION      IN (0,1) AND GENRE_ADVENTURE   IN (0,1) AND
        GENRE_ANIMATION   IN (0,1) AND GENRE_BIOGRAPHY   IN (0,1) AND
        GENRE_COMEDY      IN (0,1) AND GENRE_CRIME       IN (0,1) AND
        GENRE_DOCUMENTARY IN (0,1) AND GENRE_DRAMA       IN (0,1) AND
        GENRE_FAMILY      IN (0,1) AND GENRE_FANTASY     IN (0,1) AND
        GENRE_FILM_NOIR   IN (0,1) AND GENRE_HISTORY     IN (0,1) AND
        GENRE_HORROR      IN (0,1) AND GENRE_MUSIC       IN (0,1) AND
        GENRE_MUSICAL     IN (0,1) AND GENRE_MYSTERY     IN (0,1) AND
        GENRE_ROMANCE     IN (0,1) AND GENRE_SCI_FI      IN (0,1) AND
        GENRE_SPORT       IN (0,1) AND GENRE_THRILLER    IN (0,1) AND
        GENRE_WAR         IN (0,1) AND GENRE_WESTERN     IN (0,1)
    )
);

-- Table de transit utilisee par le processus ETL synthetique.
CREATE TABLE DW_STG_LOCATION (
    CLIENT_ID_SOURCE NUMBER NOT NULL,
    FILM_ID_SOURCE   NUMBER NOT NULL,
    DATE_LOCATION    DATE   NOT NULL
);

-- Grain : une ligne = un film loue par un client, pendant une heure donnee.
CREATE TABLE DW_FAIT_LOCATION (
    LOCATION_KEY      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLIENT_KEY        NUMBER NOT NULL,
    FILM_KEY          NUMBER NOT NULL,
    TEMPS_KEY         NUMBER NOT NULL,
    NOMBRE_LOCATIONS  NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_DW_FAIT_LOCATION PRIMARY KEY (LOCATION_KEY),
    CONSTRAINT FK_DW_FAIT_CLIENT FOREIGN KEY (CLIENT_KEY)
        REFERENCES DW_DIM_CLIENT (CLIENT_KEY),
    CONSTRAINT FK_DW_FAIT_FILM FOREIGN KEY (FILM_KEY)
        REFERENCES DW_DIM_FILM (FILM_KEY),
    CONSTRAINT FK_DW_FAIT_TEMPS FOREIGN KEY (TEMPS_KEY)
        REFERENCES DW_DIM_TEMPS (TEMPS_KEY),
    CONSTRAINT CK_DW_FAIT_NOMBRE CHECK (NOMBRE_LOCATIONS = 1)
);

-- Index utiles pour les jointures et les quatre filtres demandes.
CREATE INDEX IX_DW_FAIT_CLIENT ON DW_FAIT_LOCATION (CLIENT_KEY);
CREATE INDEX IX_DW_FAIT_FILM   ON DW_FAIT_LOCATION (FILM_KEY);
CREATE INDEX IX_DW_FAIT_TEMPS  ON DW_FAIT_LOCATION (TEMPS_KEY);
CREATE INDEX IX_DW_CLIENT_AGE  ON DW_DIM_CLIENT (GROUPE_AGE);
CREATE INDEX IX_DW_CLIENT_PROV ON DW_DIM_CLIENT (PROVINCE);
CREATE INDEX IX_DW_TEMPS_JOUR  ON DW_DIM_TEMPS (JOUR_SEMAINE);
CREATE INDEX IX_DW_TEMPS_MOIS  ON DW_DIM_TEMPS (MOIS_ANNEE);

COMMIT;

PROMPT 3/5 - Transformation et chargement de la dimension Client...

INSERT INTO DW_DIM_CLIENT (
    CLIENT_ID_SOURCE, NOM_COMPLET, AGE_ANNEES, AGE_MIN_GROUPE,
    GROUPE_AGE, DATE_PREMIERE_LOCATION, CODE_POSTAL, VILLE, PROVINCE
)
WITH CLIENTS_SOURCE AS (
    SELECT
        C.ID_CLIENT AS CLIENT_ID_SOURCE,
        TRIM(U.PRENOM || ' ' || NVL(U.NOM, '')) AS NOM_COMPLET,
        CASE
            WHEN U.DATE_NAISSANCE IS NULL THEN NULL
            ELSE TRUNC(MONTHS_BETWEEN(TRUNC(SYSDATE), U.DATE_NAISSANCE) / 12)
        END AS AGE_ANNEES,
        A.CODE_POSTAL,
        A.VILLE,
        A.PROVINCE
    FROM CLIENT C
    JOIN UTILISATEUR U
      ON U.ID = C.ID_CLIENT
    JOIN ADRESSE A
      ON A.ID_ADRESSE = C.ADRESSE_ID
), PREMIERES_LOCATIONS AS (
    SELECT CLIENT_ID_SOURCE, MIN(DATE_LOCATION) AS DATE_PREMIERE_LOCATION
    FROM DW_STG_LOCATION
    GROUP BY CLIENT_ID_SOURCE
)
SELECT
    CS.CLIENT_ID_SOURCE,
    CS.NOM_COMPLET,
    CS.AGE_ANNEES,
    CASE
        WHEN CS.AGE_ANNEES IS NULL THEN NULL
        ELSE TRUNC(CS.AGE_ANNEES / 5) * 5
    END AS AGE_MIN_GROUPE,
    CASE
        WHEN CS.AGE_ANNEES IS NULL THEN 'Inconnu'
        ELSE TO_CHAR(TRUNC(CS.AGE_ANNEES / 5) * 5)
             || '-'
             || TO_CHAR(TRUNC(CS.AGE_ANNEES / 5) * 5 + 4)
    END AS GROUPE_AGE,
    PL.DATE_PREMIERE_LOCATION,
    CS.CODE_POSTAL,
    CS.VILLE,
    CS.PROVINCE
FROM CLIENTS_SOURCE CS
LEFT JOIN PREMIERES_LOCATIONS PL
       ON PL.CLIENT_ID_SOURCE = CS.CLIENT_ID_SOURCE;

COMMIT;

PROMPT 4/5 - Transformation et chargement de la dimension Temps...

INSERT INTO DW_DIM_TEMPS (
    DATE_COMPLETE, HEURE, JOUR_SEMAINE, NUM_JOUR_SEMAINE,
    MOIS_ANNEE, NUM_MOIS, ANNEE
)
SELECT DISTINCT
    TRUNC(S.DATE_LOCATION) AS DATE_COMPLETE,
    TO_NUMBER(TO_CHAR(S.DATE_LOCATION, 'HH24')) AS HEURE,
    INITCAP(TRIM(TO_CHAR(
        S.DATE_LOCATION, 'FMDay', 'NLS_DATE_LANGUAGE=English'
    ))) AS JOUR_SEMAINE,
    1 + TRUNC(S.DATE_LOCATION) - TRUNC(S.DATE_LOCATION, 'IW')
        AS NUM_JOUR_SEMAINE,
    INITCAP(TRIM(TO_CHAR(
        S.DATE_LOCATION, 'FMMonth', 'NLS_DATE_LANGUAGE=English'
    ))) AS MOIS_ANNEE,
    TO_NUMBER(TO_CHAR(S.DATE_LOCATION, 'MM')) AS NUM_MOIS,
    TO_NUMBER(TO_CHAR(S.DATE_LOCATION, 'YYYY')) AS ANNEE
FROM DW_STG_LOCATION S;

COMMIT;

PROMPT 5/5 - Chargement de la table de faits...

INSERT INTO DW_FAIT_LOCATION (
    CLIENT_KEY, FILM_KEY, TEMPS_KEY, NOMBRE_LOCATIONS
)
SELECT
    DC.CLIENT_KEY,
    DF.FILM_KEY,
    DT.TEMPS_KEY,
    1
FROM DW_STG_LOCATION S
JOIN DW_DIM_CLIENT DC
  ON DC.CLIENT_ID_SOURCE = S.CLIENT_ID_SOURCE
JOIN DW_DIM_FILM DF
  ON DF.FILM_ID_SOURCE = S.FILM_ID_SOURCE
JOIN DW_DIM_TEMPS DT
  ON DT.DATE_COMPLETE = TRUNC(S.DATE_LOCATION)
 AND DT.HEURE = TO_NUMBER(TO_CHAR(S.DATE_LOCATION, 'HH24'));

COMMIT;

